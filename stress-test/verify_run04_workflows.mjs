// ==============================================================================
// 🧪 OUTCOME ROUTER RUN 04 WORKFLOW INTEGRATION TEST SUITE
// Tests: WF-020 through WF-024 (API Gateway Proxy, Default Keys, OpenAI v1, Security Audit, Benchmarks Eval)
// ==============================================================================

const BASE_URL = "http://localhost:3000";

let passed = 0;
let failed = 0;

function assert(condition, message, detail = "") {
  if (condition) {
    console.log(`✅ [PASS] ${message}${detail ? ` — ${detail}` : ""}`);
    passed++;
  } else {
    console.error(`❌ [FAIL] ${message}${detail ? ` — ${detail}` : ""}`);
    failed++;
  }
}

async function runRun04TestSuite() {
  console.log("================================================================");
  console.log("🚀 STARTING OUTCOME ROUTER RUN 04 WORKFLOW TEST SUITE");
  console.log("================================================================\n");

  const testEmail = `gateway_auditor_${Date.now()}@outcomerouter.ai`;

  // 1. Test WF-020: New User Registration & Default API Key Generation
  console.log("--- Testing WF-020: User Registration & Default Key Seeding ---");
  const regRes = await fetch(`${BASE_URL}/api/auth/register`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      name: "Gateway Architect",
      email: testEmail,
      workspace: "FinOps Production Lab",
      plan_tier: "growth",
      pin: "444555"
    })
  });
  const regData = await regRes.json();
  assert(regData.success, "Test user registered", regData.user?.id);

  // Fetch session to retrieve the generated default API key
  const sessionRes = await fetch(`${BASE_URL}/api/auth/session?email=${encodeURIComponent(testEmail)}`);
  const sessionData = await sessionRes.json();
  const seededKey = sessionData.user?.apiKeys?.[0];
  assert(seededKey && seededKey.full_key, "Default active API key seeded automatically", seededKey?.full_key);
  assert(seededKey?.key_prefix?.startsWith("oir_live_"), "Key prefix matches oir_live_ format", seededKey?.key_prefix);

  // 2. Test WF-021: LLM Gateway Proxy via /api/v1/chat/completions with Bearer Auth
  console.log("\n--- Testing WF-021: API Gateway Proxy Routing & Telemetry ---");
  const completionRes = await fetch(`${BASE_URL}/api/v1/chat/completions`, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "Authorization": `Bearer ${seededKey.full_key}`,
      "X-Outcome-Strategy": "outcome_optimized",
      "X-Outcome-SLA-Threshold-Ms": "150"
    },
    body: JSON.stringify({
      model: "auto",
      messages: [
        { role: "user", content: "Write a high-performance Python FastAPI route for vector embeddings." }
      ]
    })
  });

  const completionData = await completionRes.json();
  assert(completionRes.status === 200, "Gateway returned HTTP 200 OK", `Status: ${completionRes.status}`);
  assert(completionData.object === "chat.completion", "Response object is chat.completion", completionData.object);
  assert(completionData.choices?.[0]?.message?.content?.length > 0, "Response content generated by router", completionData.choices?.[0]?.message?.content?.slice(0, 45) + "...");
  assert(completionData._router_metadata?.model_routed === "DeepSeek Coder V2", "Thompson Pareto router selected DeepSeek Coder V2 for code task", completionData._router_metadata?.model_routed);
  assert(completionData._router_metadata?.account_email === testEmail, "Request attributed to authenticated user account", testEmail);
  assert(completionData._router_metadata?.capital_saved_usd > 0, "Capital saved vs GPT-4o calculated", `$${completionData._router_metadata?.capital_saved_usd}`);

  // 3. Test WF-022: Top-Level OpenAI-Compatible Wire Route /v1/chat/completions
  console.log("\n--- Testing WF-022: Top-Level OpenAI-Compatible Wire Route ---");
  const v1Res = await fetch(`${BASE_URL}/v1/chat/completions`, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "Authorization": `Bearer ${seededKey.full_key}`
    },
    body: JSON.stringify({
      messages: [{ role: "user", content: "Customer support inquiry: how do I issue a micro-SLA refund?" }]
    })
  });
  const v1Data = await v1Res.json();
  assert(v1Res.status === 200, "Top-level /v1/chat/completions endpoint returned HTTP 200 OK", `Model: ${v1Data.model}`);
  assert(v1Data._router_metadata?.model_routed === "Groq Llama 3.3 70B", "Routed support query to Groq Llama 3.3 70B LPU", v1Data._router_metadata?.model_routed);

  // 4. Test WF-023: AI Security Advisor Entropy Auditor
  console.log("\n--- Testing WF-023: AI Security Advisor Entropy Auditor ---");
  const auditRes = await fetch(`${BASE_URL}/api/settings/api-keys/audit`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ keys: [seededKey] })
  });
  const auditData = await auditRes.json();
  assert(auditData.success, "Security auditor returned audit findings", auditData.securityScore);
  assert(auditData.findings?.length === 4, "Auditor evaluated 4 cryptographic security criteria", `${auditData.findings?.length} criteria`);

  // 5. Test WF-024: Empirical Benchmark Parallel Evaluator
  console.log("\n--- Testing WF-024: Benchmark Multi-Model Parallel Evaluator ---");
  const evalRes = await fetch(`${BASE_URL}/api/benchmarks/eval`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ task_type: "code_generation" })
  });
  const evalData = await evalRes.json();
  assert(evalData.success, "Benchmark evaluation returned multi-model audit results", `${evalData.totalAuditedModels} models`);
  assert(evalData.results?.length === 5, "Evaluated 5 frontier models across latency and cost", `${evalData.results?.length} models`);

  // 6. Cleanup test account
  await fetch(`${BASE_URL}/api/auth/delete-account`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ email: testEmail })
  });

  console.log("\n================================================================");
  console.log(`📊 RUN 04 TEST SUMMARY: ${passed} / ${passed + failed} TESTS PASSED (${((passed / (passed + failed)) * 100).toFixed(1)}%)`);
  console.log("================================================================");

  if (failed > 0) {
    process.exit(1);
  }
}

runRun04TestSuite();
